    read -p '(default: n):' libev_obfs
    [ -z "$libev_obfs" ] && libev_obfs=n
    case "${libev_obfs}" in
        y|Y|n|N)
        echo
        echo "You choose = ${libev_obfs}"
        echo
        break
        ;;
        *)
        echo -e "[${red}Error${plain}] Please only enter [y/n]"
        ;;
