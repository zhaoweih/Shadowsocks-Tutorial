disable_selinux(){
    if [ -s /etc/selinux/config ] && grep 'SELINUX=enforcing' /etc/selinux/config; then
        sed -i 's/SELINUX=enforcing/SELINUX=disabled/g' /etc/selinux/config
        setenforce 0
    fi
}

check_sys(){
    local checkType=$1
    local value=$2

    local release=''
    local systemPackage=''

    if [[ -f /etc/redhat-release ]]; then
        release='centos'
        systemPackage='yum'
    elif grep -Eqi 'debian|raspbian' /etc/issue; then
        release='debian'
        systemPackage='apt'
    elif grep -Eqi 'ubuntu' /etc/issue; then
        release='ubuntu'
        systemPackage='apt'
    elif grep -Eqi 'centos|red hat|redhat' /etc/issue; then
        release='centos'
        systemPackage='yum'
    elif grep -Eqi 'debian|raspbian' /proc/version; then
        release='debian'
        systemPackage='apt'
    elif grep -Eqi 'ubuntu' /proc/version; then
        release='ubuntu'
        systemPackage='apt'
    elif grep -Eqi 'centos|red hat|redhat' /proc/version; then
        release='centos'
        systemPackage='yum'
    fi

    if [[ "${checkType}" == 'sysRelease' ]]; then
        if [ "${value}" == "${release}" ]; then
            return 0
        else
            return 1
        fi
    elif [[ "${checkType}" == 'packageManager' ]]; then
        if [ "${value}" == "${systemPackage}" ]; then
            return 0
        else
            return 1
        fi
    fi
}

check_systemd(){
    if [ ! -d /run/systemd/system ] || ! command -v systemctl > /dev/null 2>&1; then
        echo -e "[${red}Error${plain}] systemd is required (Debian 8+, Ubuntu 16.04+, CentOS 7+)."
        exit 1
    fi
}

get_ip(){
    local IP
    IP=$( ip addr | grep -Eo '[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}' | grep -Ev '^192\.168|^172\.1[6-9]\.|^172\.2[0-9]\.|^172\.3[0-2]\.|^10\.|^127\.|^255\.|^0\.' | head -n 1 )
    [ -z "${IP}" ] && IP=$( wget -qO- -t1 -T2 ipv4.icanhazip.com )
    [ -z "${IP}" ] && IP=$( wget -qO- -t1 -T2 ipinfo.io/ip )
    echo "${IP}"
}

# true when the machine has a global IPv6 address (no network access needed)
get_ipv6(){
    ip -6 addr show scope global 2> /dev/null | grep -q 'inet6'
}

get_char(){
    SAVEDSTTY=$(stty -g)
    stty -echo
    stty cbreak
    dd if=/dev/tty bs=1 count=1 2> /dev/null
    stty -raw
    stty echo
    stty "$SAVEDSTTY"
}

# verify_sha256 <file> <expected sha256>
verify_sha256(){
    echo "${2}  ${1}" | sha256sum -c --status > /dev/null 2>&1
}

# download <file name> [upstream url]
# The file is looked up in this order, each candidate is verified against the
# checksum table: the current directory, ../vendor (repository clone), the
# vendored copy in the repository, and finally the upstream project.
download(){
    local filename=$1
    local upstream=$2
    local expected="${vendor_sha256[${filename}]}"
    local target="${cur_dir}/${filename}"
    local url

    if [ -z "${expected}" ]; then
        echo -e "[${red}Error${plain}] No checksum for ${filename} in this script, please re-download the script."
        return 1
    fi

    if [ -f "${target}" ]; then
        if verify_sha256 "${target}" "${expected}"; then
            echo "${filename} [found]"
            return 0
        fi
        echo -e "[${yellow}Warning${plain}] ${filename} exists but its checksum does not match, downloading again..."
        rm -f "${target}"
    fi

    if [ -f "${vendor_dir}/${filename}" ] && verify_sha256 "${vendor_dir}/${filename}" "${expected}"; then
        cp "${vendor_dir}/${filename}" "${target}"
        echo "${filename} [vendor]"
        return 0
    fi

    for url in "${vendor_url}/${filename}" ${upstream}; do
        echo "${filename} not found, download now from ${url}"
        if wget -t3 -T60 -O "${target}" "${url}" && verify_sha256 "${target}" "${expected}"; then
            return 0
        fi
        echo -e "[${yellow}Warning${plain}] ${url} failed or checksum mismatch"
        rm -f "${target}"
    done

    echo -e "[${red}Error${plain}] Download ${filename} failed."
    return 1
}

error_detect_depends(){
    local command=$1
    local depend
    depend=$(echo "${command}" | awk '{print $4}')
    echo -e "[${green}Info${plain}] Starting to install package ${depend}"
    echo "### ${command}" >> "${depends_log}"
    ${command} >> "${depends_log}" 2>&1
    if [ $? -ne 0 ]; then
        echo -e "[${red}Error${plain}] Failed to install ${red}${depend}${plain}"
        echo "Last lines of ${depends_log}:"
        tail -n 20 "${depends_log}"
        exit 1
    fi
}

# libev-devel lives in EPEL; if that still fails (see #72), build libev from source.
install_libev_centos(){
    if yum -y install libev-devel >> "${depends_log}" 2>&1; then
        return 0
    fi
    echo -e "[${yellow}Warning${plain}] libev-devel not available from yum, building libev from source..."
    cd "${cur_dir}" || exit
    download "${libev_file}.tar.gz" "${libev_upstream}" || exit 1
    tar zxf "${libev_file}.tar.gz"
    cd "${libev_file}" || exit
    ./configure --prefix=/usr && make && make install
    if [ $? -ne 0 ]; then
        echo -e "[${red}Error${plain}] ${libev_file} install failed."
        install_cleanup
        exit 1
    fi
    ldconfig
    cd "${cur_dir}" || exit
}

install_dependencies(){
    if check_sys packageManager yum; then
        echo -e "[${green}Info${plain}] Checking the EPEL repository..."
        if [ ! -f /etc/yum.repos.d/epel.repo ]; then
            yum install -y epel-release > /dev/null 2>&1
        fi
        [ ! -f /etc/yum.repos.d/epel.repo ] && echo -e "[${red}Error${plain}] Install EPEL repository failed, please check it." && exit 1
        [ ! "$(command -v yum-config-manager)" ] && yum install -y yum-utils > /dev/null 2>&1
        [ x"$(yum-config-manager epel | grep -w enabled | awk '{print $3}')" != x'True' ] && yum-config-manager --enable epel > /dev/null 2>&1
        echo -e "[${green}Info${plain}] Checking the EPEL repository complete..."

        yum_depends=(
            wget gzip openssl openssl-devel gcc pcre pcre-devel libtool
            autoconf automake make curl zlib-devel perl cpio expat-devel gettext-devel
            c-ares-devel qrencode
        )
        for depend in ${yum_depends[@]}; do
            error_detect_depends "yum -y install ${depend}"
        done
        install_libev_centos
    elif check_sys packageManager apt; then
        apt_depends=(
            wget gzip gettext build-essential curl openssl libssl-dev
            autoconf automake libtool gcc make perl libpcre3 libpcre3-dev zlib1g-dev libev-dev libc-ares-dev qrencode
        )

        apt-get -y update >> "${depends_log}" 2>&1

        for depend in ${apt_depends[@]}; do
            error_detect_depends "apt-get -y install ${depend}"
        done
    fi
}

install_check(){
    if check_sys packageManager yum || check_sys packageManager apt; then
        return 0
    else
        return 1
    fi
}

install_prepare_password(){
    while true
    do
    echo "Please enter password for Shadowsocks-libev"
    read -r -p '(Default password: teddysun.com):' shadowsockspwd
    [ -z "${shadowsockspwd}" ] && shadowsockspwd='teddysun.com'
    # the password is written into config.json verbatim
    if [[ "${shadowsockspwd}" == *[\"\\]* ]]; then
        echo -e "[${red}Error${plain}] Password must not contain double quotes or backslashes"
        continue
    fi
    echo
    echo "password = ${shadowsockspwd}"
    echo
    break
    done
}

install_prepare_port() {
    while true
    do
    dport=$(shuf -i 9000-19999 -n 1)
    echo -e "Please enter a port for Shadowsocks-libev [1-65535]"
    read -p "(Default port: ${dport}):" shadowsocksport
    [ -z "${shadowsocksport}" ] && shadowsocksport=${dport}
    expr "${shadowsocksport}" + 1 &>/dev/null
    if [ $? -eq 0 ]; then
        if [ "${shadowsocksport}" -ge 1 ] && [ "${shadowsocksport}" -le 65535 ] && [ "${shadowsocksport:0:1}" != 0 ]; then
            echo
            echo "port = ${shadowsocksport}"
            echo
            break
        fi
    fi
    echo -e "[${red}Error${plain}] Please enter a correct number [1-65535]"
    done
}

install_prepare_cipher(){
    while true
    do
    echo -e "Please select stream cipher for Shadowsocks-libev:"
    for ((i=1;i<=${#common_ciphers[@]};i++ )); do
        hint="${common_ciphers[$i-1]}"
        echo -e "${green}${i}${plain}) ${hint}"
    done
    read -p "Which cipher you'd select(Default: ${common_ciphers[0]}):" pick
    [ -z "$pick" ] && pick=1
    expr ${pick} + 1 &>/dev/null
    if [ $? -ne 0 ]; then
        echo -e "[${red}Error${plain}] Please enter a number"
        continue
    fi
    if [[ "$pick" -lt 1 || "$pick" -gt ${#common_ciphers[@]} ]]; then
        echo -e "[${red}Error${plain}] Please enter a number between 1 and ${#common_ciphers[@]}"
        continue
    fi
    shadowsockscipher=${common_ciphers[$pick-1]}
    echo
    echo "cipher = ${shadowsockscipher}"
    echo
    break
    done
}

