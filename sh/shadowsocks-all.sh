install_simple_obfs(){
    if [ "${libev_obfs}" == 'y' ] || [ "${libev_obfs}" == 'Y' ]; then
        cd "${cur_dir}" || exit
        if [ ! -d simple-obfs ]; then
            tar zxf "${simple_obfs_file}".tar.gz
        fi
        cd simple-obfs || exit
        ./autogen.sh && ./configure --disable-documentation && make && make install
        if [ ! "$(command -v obfs-server)" ]; then
            echo -e "[${red}Error${plain}] simple-obfs install failed."
            install_cleanup
            exit 1
