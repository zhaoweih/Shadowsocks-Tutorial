    done

    if [ "${libev_obfs}" == 'y' ] || [ "${libev_obfs}" == 'Y' ]; then
        while true
        do
        echo -e 'Please select obfs for simple-obfs:'
        for ((i=1;i<=${#obfs_libev[@]};i++ )); do
            hint="${obfs_libev[$i-1]}"
            echo -e "${green}${i}${plain}) ${hint}"
        done
        read -p "Which obfs you'd select(Default: ${obfs_libev[0]}):" r_libev_obfs
        [ -z "$r_libev_obfs" ] && r_libev_obfs=1
        expr ${r_libev_obfs} + 1 &>/dev/null
        if [ $? -ne 0 ]; then
            echo -e "[${red}Error${plain}] Please enter a number"
            continue
        fi
        if [[ "$r_libev_obfs" -lt 1 || "$r_libev_obfs" -gt ${#obfs_libev[@]} ]]; then
            echo -e "[${red}Error${plain}] Please enter a number between 1 and ${#obfs_libev[@]}"
            continue
        fi
        shadowsocklibev_obfs=${obfs_libev[$r_libev_obfs-1]}
        echo
        echo "obfs = ${shadowsocklibev_obfs}"
        echo
        break
        done
    fi
}

install_prepare(){
    if ! install_check; then
        echo -e "[${red}Error${plain}] Your OS is not supported to run it!"
        echo 'Please change to Debian 8+/Ubuntu 16.04+/CentOS 7+ and try again.'
        exit 1
    fi
    check_systemd

    clear
    install_prepare_password
    install_prepare_port
    install_prepare_cipher
    install_prepare_libev_obfs

    echo
    echo 'Press any key to start...or Press Ctrl+C to cancel'
    char=$(get_char)
}

# Fetch everything before compiling anything, so a missing file fails fast.
download_files(){
    cd "${cur_dir}" || exit
    [ ! -f /usr/lib/libsodium.a ] && { download "${libsodium_file}.tar.gz" "${libsodium_upstream}" || exit 1; }
    [ ! -f /usr/lib/libmbedtls.a ] && { download "${mbedtls_file}.tar.gz" "${mbedtls_upstream}" || exit 1; }
    download "${shadowsocks_libev_file}.tar.gz" "${shadowsocks_libev_upstream}" || exit 1
    if [ "${libev_obfs}" == 'y' ] || [ "${libev_obfs}" == 'Y' ]; then
        download "${simple_obfs_file}.tar.gz" || fetch_simple_obfs_git || exit 1
    fi
}

# Last resort for simple-obfs: there is no upstream tarball, clone the pinned commit.
fetch_simple_obfs_git(){
    echo -e "[${yellow}Warning${plain}] Falling back to git clone for simple-obfs..."
    if ! command -v git > /dev/null 2>&1; then
        if check_sys packageManager yum; then
            error_detect_depends "yum -y install git"
        else
            error_detect_depends "apt-get -y install git"
        fi
    fi
    rm -rf "${cur_dir}/simple-obfs"
    git clone "${simple_obfs_repo}" "${cur_dir}/simple-obfs" || return 1
    git -C "${cur_dir}/simple-obfs" checkout -q "${simple_obfs_commit}" || return 1
    git -C "${cur_dir}/simple-obfs" submodule update --init --recursive || return 1
}

config_shadowsocks(){
    local server_value="\"0.0.0.0\""
    if get_ipv6; then
        server_value="[\"[::0]\",\"0.0.0.0\"]"
    fi

    if [ ! -d "$(dirname ${shadowsocks_libev_config})" ]; then
        mkdir -p $(dirname ${shadowsocks_libev_config})
    fi

    if [ "${libev_obfs}" == 'y' ] || [ "${libev_obfs}" == 'Y' ]; then
        cat > ${shadowsocks_libev_config}<<-EOF
{
    "server":${server_value},
    "server_port":${shadowsocksport},
    "password":"${shadowsockspwd}",
    "timeout":300,
    "user":"nobody",
    "method":"${shadowsockscipher}",
    "fast_open":false,
    "nameserver":"1.0.0.1",
    "mode":"tcp_and_udp",
    "plugin":"obfs-server",
    "plugin_opts":"obfs=${shadowsocklibev_obfs}"
}
EOF
    else
        cat > ${shadowsocks_libev_config}<<-EOF
{
    "server":${server_value},
    "server_port":${shadowsocksport},
    "password":"${shadowsockspwd}",
    "timeout":300,
    "user":"nobody",
    "method":"${shadowsockscipher}",
    "fast_open":false,
    "nameserver":"1.0.0.1",
    "mode":"tcp_and_udp"
}
EOF
    fi
}

config_firewall(){
    if check_sys packageManager apt; then
        if command -v ufw > /dev/null 2>&1 && ufw status 2> /dev/null | grep -q '^Status: active'; then
            ufw allow "${shadowsocksport}"/tcp > /dev/null 2>&1
            ufw allow "${shadowsocksport}"/udp > /dev/null 2>&1
            echo -e "[${green}Info${plain}] ufw is active, port ${green}${shadowsocksport}${plain} (tcp/udp) has been allowed."
        fi
    else
        if command -v firewall-cmd > /dev/null 2>&1 && firewall-cmd --state > /dev/null 2>&1; then
            default_zone=$(firewall-cmd --get-default-zone)
            firewall-cmd --permanent --zone="${default_zone}" --add-port="${shadowsocksport}"/tcp
            firewall-cmd --permanent --zone="${default_zone}" --add-port="${shadowsocksport}"/udp
            firewall-cmd --reload
        else
            echo -e "[${yellow}Warning${plain}] firewalld looks like not running or not installed, please enable port ${shadowsocksport} manually if necessary."
        fi
    fi
}

