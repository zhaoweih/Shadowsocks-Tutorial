        [ -f /usr/local/bin/obfs-server ] && [ ! -e /usr/bin/obfs-server ] && ln -s /usr/local/bin/obfs-server /usr/bin
    fi
}

# Replace an installation done by the old SysV init script version of this script.
remove_legacy_init(){
    if [ -f "${legacy_init}" ]; then
        echo -e "[${green}Info${plain}] Removing the old init script ${legacy_init}"
        "${legacy_init}" stop > /dev/null 2>&1
        if check_sys packageManager yum; then
            chkconfig --del "$(basename ${legacy_init})" > /dev/null 2>&1
        else
            update-rc.d -f "$(basename ${legacy_init})" remove > /dev/null 2>&1
        fi
        rm -f "${legacy_init}"
    fi
}

install_service(){
    remove_legacy_init
    cat > "${service_file}"<<-EOF
[Unit]
Description=Shadowsocks-libev server
Documentation=https://github.com/zhaoweih/Shadowsocks-Tutorial
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=/usr/local/bin/ss-server -c ${shadowsocks_libev_config}
Restart=on-failure
RestartSec=3s
LimitNOFILE=51200

[Install]
WantedBy=multi-user.target
EOF
    systemctl daemon-reload
    systemctl enable "${service_name}" > /dev/null 2>&1
    systemctl restart "${service_name}"
    sleep 2
    if systemctl is-active --quiet "${service_name}"; then
        echo -e "[${green}Info${plain}] Starting Shadowsocks-libev success"
    else
        echo -e "[${red}Error${plain}] Shadowsocks-libev failed to start:"
        journalctl -u "${service_name}" -n 20 --no-pager
        exit 1
    fi
}

