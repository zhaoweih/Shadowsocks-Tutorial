}

qr_generate(){
    if [ "$(command -v qrencode)" ]; then
        local tmp
        tmp=$(echo -n "${shadowsockscipher}:${shadowsockspwd}@$(get_ip):${shadowsocksport}" | base64 -w0)
        local qr_code="ss://${tmp}"
        echo
        echo 'Your QR Code: (For Shadowsocks Windows, OSX, Android and iOS clients)'
        echo -e "${green} ${qr_code} ${plain}"
        echo -n "${qr_code}" | qrencode -s8 -o "${cur_dir}"/shadowsocks_libev_qr.png
        echo 'Your QR Code has been saved as a PNG file path:'
        echo -e "${green} ${cur_dir}/shadowsocks_libev_qr.png ${plain}"
    fi
}

install_cleanup(){
    cd "${cur_dir}" || exit
    rm -rf simple-obfs "${simple_obfs_file}".tar.gz
    rm -rf "${libsodium_file}" "${libsodium_file}".tar.gz
    rm -rf "${mbedtls_file}" "${mbedtls_file}".tar.gz
    rm -rf "${libev_file}" "${libev_file}".tar.gz
    rm -rf "${shadowsocks_libev_file}" "${shadowsocks_libev_file}".tar.gz
}

install_shadowsocks(){
    disable_selinux
    install_prepare
    install_dependencies
    download_files
    config_shadowsocks
    config_firewall
    install_libsodium
    if ! ldconfig -p | grep -wq '/usr/lib'; then
        echo '/usr/lib' > /etc/ld.so.conf.d/lib.conf
    fi
    ldconfig
    install_mbedtls
    install_shadowsocks_libev
    install_simple_obfs
    ldconfig
    install_service
    install_completed
    qr_generate
    install_cleanup
    echo
    echo 'Enjoy it!'
    echo
}

uninstall_shadowsocks(){
    if [ ! -f "${service_file}" ] && [ ! -f "${legacy_init}" ]; then
        echo -e "[${red}Error${plain}] Shadowsocks-libev not installed, please check it and try again."
        exit 1
    fi
    printf "Are you sure uninstall ${red}Shadowsocks-libev${plain}? [y/n]\n"
    read -p '(default: n):' answer
    [ -z "${answer}" ] && answer='n'
    if [ "${answer}" == 'y' ] || [ "${answer}" == 'Y' ]; then
        if [ -f "${service_file}" ]; then
            systemctl disable --now "${service_name}" > /dev/null 2>&1
            rm -f "${service_file}"
            systemctl daemon-reload
        fi
        remove_legacy_init
        rm -fr $(dirname ${shadowsocks_libev_config})
        rm -f /usr/local/bin/ss-local
        rm -f /usr/local/bin/ss-tunnel
        rm -f /usr/local/bin/ss-server
        rm -f /usr/local/bin/ss-manager
        rm -f /usr/local/bin/ss-redir
        rm -f /usr/local/bin/ss-nat
        rm -f /usr/local/bin/obfs-local
        rm -f /usr/local/bin/obfs-server
        rm -f /usr/bin/obfs-server
        rm -f /usr/local/lib/libshadowsocks-libev.a
        rm -f /usr/local/lib/libshadowsocks-libev.la
        rm -f /usr/local/include/shadowsocks.h
        rm -f /usr/local/lib/pkgconfig/shadowsocks-libev.pc
        rm -f /usr/local/share/man/man1/ss-local.1
        rm -f /usr/local/share/man/man1/ss-tunnel.1
        rm -f /usr/local/share/man/man1/ss-server.1
        rm -f /usr/local/share/man/man1/ss-manager.1
        rm -f /usr/local/share/man/man1/ss-redir.1
        rm -f /usr/local/share/man/man1/ss-nat.1
        rm -f /usr/local/share/man/man8/shadowsocks-libev.8
        rm -fr /usr/local/share/doc/shadowsocks-libev
        echo -e "[${green}Info${plain}] Shadowsocks-libev uninstall success"
    else
        echo
        echo -e "[${green}Info${plain}] Shadowsocks-libev uninstall cancelled, nothing to do..."
        echo
    fi
}

